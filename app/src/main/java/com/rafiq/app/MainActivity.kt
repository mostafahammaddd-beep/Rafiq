fun normRawWord(s: String, preserveTanweenFath: Boolean = true): String {
    val hasTanweenFath = preserveTanweenFath && s.contains('ً')
    val sb = StringBuilder()
    for (ch in s) {
        val c = ch.code
        if (c in 0x064B..0x065F || c == 0x0670 || c == 0x0640 || c in 0x06D6..0x06ED) continue
        when (ch) {
            'أ', 'إ', 'آ', 'ٱ' -> sb.append('ا')
            'ى', 'ی', 'ئ' -> sb.append('ي')
            'ؤ' -> sb.append('و')
            'ة' -> sb.append('ه')
            'ک' -> sb.append('ك')
            'ء' -> { }
            else -> if (c in 0x0621..0x064A) sb.append(ch)
        }
    }
    val canon = when (val res = sb.toString()) {
        "السموات" -> "السماوات"
        "الاه" -> "اله"
        "يووده", "ييوده", "ياوده", "يوده" -> "يوده"
        "بشيي" -> "بشي"
        "شاا" -> "شا"
        else -> res
    }
    return if (hasTanweenFath) "${canon}ً" else canon
}

fun norm(s: String): String {
    val tokens = s.trim().split(Regex("\\s+")).filter { it.isNotEmpty() }
    if (tokens.isEmpty()) return normRawWord(s, preserveTanweenFath = false)
    val joined = tokens.joinToString("") { normRawWord(it, preserveTanweenFath = false) }
    return joined
        .replace("السموات", "السماوات")
        .replace("يووده", "يوده")
        .replace("ييوده", "يوده")
        .replace("بشيي", "بشي")
}

