class AlignResult(
    val st: Array<WS?>,
    val heard: Array<String>,
    val notes: Array<String>,
    val trapHit: BooleanArray,
    val subOrInsCost: FloatArray,
    val first: Int,
    val last: Int,
    val bad: Int,
    val score: Float
)

object Aligner {
    private const val INF = 1e9f
    private const val SKIP = 0.85f
    private const val MATCH_BONUS = -0.04f
    private const val SUB_COST = 0.72f
    private const val GAP_COST = 0.95f

    fun align(rawText: String, base: Int, isFinal: Boolean): AlignResult? {
        val rawTokens = TashkeelAndMakhrajChecker.preprocessRawTokens(rawText, base)
        if (rawTokens.isEmpty()) return null

        val hSb = StringBuilder()
        val tokOwnerList = ArrayList<Int>()
        for (tIdx in rawTokens.indices) {
            val nt = normRawWord(rawTokens[tIdx], preserveTanweenFath = true)
            for (ch in nt) {
                hSb.append(ch)
                tokOwnerList.add(tIdx)
            }
        }
        val h = hSb.toString()
        val m = h.length
        if (m == 0) return null

        val n = WORDS.size
        val lookbackBase = maxOf(0, base - 4)
        val s0 = W_START[lookbackBase]
        val rl = REF.length - s0
        val w = rl + 1
        val d = FloatArray((m + 1) * w) { INF }
        val bp = ByteArray((m + 1) * w)

        val baseOffset = W_START[base] - s0
        for (wi in lookbackBase until minOf(n, base + 4)) {
            val jStart = W_START[wi] - s0
            d[jStart] = if (wi <= base) 0f else SKIP * (jStart - baseOffset)
        }

        for (i in 1..m) {
            val hi = h[i - 1]
            val row = i * w
            val prev = (i - 1) * w
            for (j in 0..rl) {
                var best = INF
                var b = 0
                if (j > 0) {
                    val v0 = d[prev + j - 1]
                    if (v0 < INF) {
                        val v = v0 + (if (hi == REF[s0 + j - 1]) MATCH_BONUS else SUB_COST)
                        if (v < best) { best = v; b = 1 }
                    }
                }
                val v1 = d[prev + j]
                if (v1 < INF) {
                    val v = v1 + GAP_COST
                    if (v < best) { best = v; b = 2 }
                }
                if (j > 0) {
                    val v2 = d[row + j - 1]
                    if (v2 < INF) {
                        val v = v2 + GAP_COST
                        if (v < best) { best = v; b = 3 }
                    }
                    val c = s0 + j - 1
                    val wi = OWNER[c]
                    if (c + 1 == W_END[wi]) {
                        val js = W_START[wi] - s0
                        if (js >= 0) {
                            val v3 = d[row + js]
                            if (v3 < INF) {
                                val v = v3 + SKIP * NW[wi].length
                                if (v < best) { best = v; b = 4 }
                            }
                        }
                    }
                }
                d[row + j] = best
                bp[row + j] = b.toByte()
            }
        }

        var je = 0
        var bc = INF
        for (j in 0..rl) {
            val v = d[m * w + j]
            if (v <= bc + 1e-6f) { bc = v; je = j }
        }
        if (bc >= INF) return null

        val cost = FloatArray(n)
        val subOrInsCost = FloatArray(n)
        val heardRev = Array(n) { StringBuilder() }
        val wordTokIndices = Array(n) { LinkedHashSet<Int>() }
        val skipped = BooleanArray(n)
        var i = m
        var j = je
        var matched = 0
        while (true) {
            val b = bp[i * w + j].toInt()
            if (i == 0 || b == 0) break
            when (b) {
                1 -> {
                    val col = s0 + j - 1
                    val wi = OWNER[col]
                    if (h[i - 1] == REF[col]) {
                        matched++
                    } else {
                        cost[wi] += 1f
                        subOrInsCost[wi] += 1f
                    }
                    heardRev[wi].append(h[i - 1])
                    wordTokIndices[wi].add(tokOwnerList[i - 1])
                    i--; j--
                }
                2 -> {
                    val insTok = tokOwnerList[i - 1]
                    val leftCol = (s0 + j - 1).coerceIn(s0, REF.length - 1)
                    val rightCol = (s0 + j).coerceIn(s0, REF.length - 1)
                    val leftW = OWNER[leftCol]
                    val rightW = OWNER[rightCol]
                    val targetW = if (leftW != rightW && !wordTokIndices[leftW].contains(insTok)) rightW else leftW
                    cost[targetW] += 1f
                    subOrInsCost[targetW] += 1f
                    heardRev[targetW].append(h[i - 1])
                    wordTokIndices[targetW].add(insTok)
                    i--
                }
                3 -> {
                    val col = s0 + j - 1
                    cost[OWNER[col]] += 1f
                    j--
                }
                else -> {
                    val wi = OWNER[s0 + j - 1]
                    skipped[wi] = true
                    j = W_START[wi] - s0
                }
            }
        }
        val startCol = s0 + j
        val endCol = s0 + je
        if (endCol <= startCol || matched == 0 || matched * 2 < m) return null

        val st = arrayOfNulls<WS>(n)
        val heard = Array(n) { "" }
        val notes = Array(n) { "" }
        val trapHit = BooleanArray(n)
        val first = OWNER[startCol]
        val last = OWNER[endCol - 1]

        if (first > base && (isFinal || (last - first >= 1))) {
            for (wi in base until first) {
                st[wi] = WS.WRONG
                notes[wi] = "لم أسمع هذه الكلمة منك (قد تكون تخطيتَها أثناء التسميع)."
            }
        }

        val evalStart = maxOf(base, first)
        for (wi in evalStart..last) {
            heard[wi] = heardRev[wi].reverse().toString()
            if (skipped[wi]) {
                if (isFinal || (last - wi >= 1)) {
                    st[wi] = WS.WRONG
                    notes[wi] = "لم أسمع هذه الكلمة منك (قد تكون تخطيتَها أثناء التسميع)."
                }
                continue
            }

            for (tIdx in wordTokIndices[wi]) {
                if (tIdx in rawTokens.indices) {
                    val tConflict = TashkeelAndMakhrajChecker.checkWordTrapAndDiacritics(rawTokens[tIdx], wi)
                    if (tConflict != null) {
                        cost[wi] += 1f
                        subOrInsCost[wi] += 1f
                        notes[wi] = tConflict
                        trapHit[wi] = true
                        break
                    }
                }
            }

            if (wi < last) {
                // إذا انتقل القارئ إلى الكلمة التالية وكانت الكلمة wi ناقصة (مثل قول «حفظهم» بدل «حفظهما» أو «يحيط» بدل «يحيطون»)،
                // نحسب الحروف الناقصة من آخر wi خطأً فوراً!
                val missingTail = if (heard[wi].length < NW[wi].length) (NW[wi].length - heard[wi].length).toFloat() else 0f
                val totalWordCost = cost[wi] + missingTail
                val nextCharsMatched = endCol - W_START[wi + 1]
                val nextConfirmed = nextCharsMatched >= min(2, NW[wi + 1].length)
                if (totalWordCost <= 1e-4f) {
                    st[wi] = WS.OK
                } else if (trapHit[wi] || subOrInsCost[wi] >= 1f || nextConfirmed || isFinal || (last - wi >= 2)) {
                    st[wi] = WS.WRONG
                    if (notes[wi].isEmpty()) {
                        notes[wi] = TashkeelAndMakhrajChecker.diagnoseOrthographicError(wi, NW[wi], heard[wi])
                    }
                }
            } else if (endCol >= W_END[wi]) {
                if (cost[wi] <= 1e-4f) {
                    st[wi] = WS.OK
                } else if (trapHit[wi] || isFinal) {
                    st[wi] = WS.WRONG
                    if (notes[wi].isEmpty()) {
                        notes[wi] = TashkeelAndMakhrajChecker.diagnoseOrthographicError(wi, NW[wi], heard[wi])
                    }
                }
            } else {
                if (trapHit[wi]) {
                    st[wi] = WS.WRONG
                }
            }
        }
        var bad = 0
        for (wi in base until n) if (st[wi] == WS.WRONG) bad++
        return AlignResult(st, heard, notes, trapHit, subOrInsCost, first, last, bad, matched.toFloat() - bc)
    }
}

class Engine(private val ctx: Context) {
    var phase by mutableStateOf(Phase.SETUP)
    var target by mutableStateOf(3)
    var counter by mutableStateOf(3)
    var playing by mutableStateOf(false)
    var status by mutableStateOf("")
    var showAll by mutableStateOf(true)
    var current by mutableStateOf(0)
    val states = mutableStateListOf<WS>().apply { repeat(WORDS.size) { add(WS.PENDING) } }
    val heard = Array(WORDS.size) { "" }
    val notes = Array(WORDS.size) { "" }

    private val lockedWrongNotes = Array(WORDS.size) { "" }
    private val lockedWrongHeard = Array(WORDS.size) { "" }
    private val lastWordWrongStreak = IntArray(WORDS.size)
    private var auditedUpToWord = 0
    private var pendingTailAuditWord = -1

    private val h = Handler(Looper.getMainLooper())
    private var rec: SpeechRecognizer? = null
    private var player: MediaPlayer? = null
    private var session = 0
    private var base = 0
    private var sBase = 0
    private var lastR: AlignResult? = null
    private var stopping = false
    private var lastActivity = 0L
    private val beeped = BooleanArray(WORDS.size)
    private val tone: ToneGenerator? = try {
        ToneGenerator(AudioManager.STREAM_NOTIFICATION, 70)
    } catch (e: Exception) { null }

    fun success() = states.all { it == WS.OK }

    fun startCycle() { counter = target; goGuided() }

    private fun resetAttempt() {
        for (i in states.indices) {
            states[i] = WS.PENDING
            heard[i] = ""
            notes[i] = ""
            lockedWrongNotes[i] = ""
            lockedWrongHeard[i] = ""
            lastWordWrongStreak[i] = 0
            beeped[i] = false
        }
        base = 0
        sBase = 0
        auditedUpToWord = 0
        pendingTailAuditWord = -1
        lastR = null
        current = 0
        lastActivity = SystemClock.elapsedRealtime()
        AcousticStreamAuditor.resetSession()
    }

    fun goGuided() {
        stopRec(); stopAudio(); h.removeCallbacksAndMessages(null)
        resetAttempt(); phase = Phase.GUIDED
        status = "اقرأ الآية بصوتك… (التوهج الذهبي يتابعك كلمة بكلمة تلقائياً)"
        startRec()
    }

    fun goRecite() {
        stopRec(); stopAudio(); h.removeCallbacksAndMessages(null)
        resetAttempt(); phase = Phase.RECITE
        status = "سَمِّع الآية غيباً… (الرصد تلقائي مع التوهج المتحرك)"
        startRec()
        tick()
    }

    fun restartAttempt() {
        stopRec(); stopAudio(); h.removeCallbacksAndMessages(null)
        resetAttempt()
        status = "اقرأ الآية بصوتك…"
        if (phase == Phase.GUIDED || phase == Phase.RECITE) startRec()
        if (phase == Phase.RECITE) tick()
    }

    fun finish() {
        stopRec(); AcousticStreamAuditor.stopAll(); h.removeCallbacksAndMessages(null)
        for (i in states.indices) if (states[i] == WS.PENDING) states[i] = WS.WRONG
        current = WORDS.size
        phase = Phase.RESULT
    }

    fun explain(i: Int): String {
        val sb = StringBuilder()
        if (notes[i].isNotEmpty()) {
            sb.append(notes[i])
            if (heard[i].isNotEmpty() && !notes[i].contains("سمعتُ منك")) {
                sb.append("\n\nسمعتُ منك: «").append(heard[i]).append("»\nوالصواب: ").append(WORDS[i])
            }
        } else if (states[i] == WS.HINT) {
            sb.append("نسيتَ هذه الكلمة فلُقِّنتَها. أعد حفظ موضعها جيداً.")
        } else {
            sb.append(TashkeelAndMakhrajChecker.diagnoseOrthographicError(i, NW[i], heard[i]))
        }
        TIPS[i]?.let { sb.append("\n\nتذكير بحكم الكلمة: ").append(it) }
        return sb.toString()
    }

    private fun refreshCurrent() {
        var c = states.indexOfFirst { it == WS.PENDING }
        if (c < 0) c = WORDS.size
        if (c != current) {
            current = c
            lastActivity = SystemClock.elapsedRealtime()
        }
    }

    private fun allDecided(): Boolean = states.none { it == WS.PENDING }

    private fun tick() {
        h.postDelayed({
            if (phase != Phase.RECITE) return@postDelayed
            val now = SystemClock.elapsedRealtime()
            val i = current
            if (now - lastActivity >= 7000 && i < WORDS.size && states[i] == WS.PENDING) {
                states[i] = WS.HINT; lastActivity = now; refreshCurrent()
            }
            tick()
        }, 500)
    }

    private fun startRec() {
        stopRec()
        if (!SpeechRecognizer.isRecognitionAvailable(ctx)) {
            status = "خدمة التعرف على الصوت غير متوفرة على هذا الجهاز"
            return
        }
        val id = ++session
        sBase = base
        lastR = null
        stopping = false
        val r = SpeechRecognizer.createSpeechRecognizer(ctx)
        rec = r
        r.setRecognitionListener(object : RecognitionListener {
            override fun onReadyForSpeech(p: Bundle?) {}
            override fun onBeginningOfSpeech() {
                AcousticStreamAuditor.notifyRecognizerAlive()
            }
            override fun onRmsChanged(v: Float) {
                AcousticStreamAuditor.onRmsChanged(v)
            }
            override fun onBufferReceived(b: ByteArray?) {}
            override fun onEndOfSpeech() {}
            override fun onEvent(t: Int, b: Bundle?) {}
            override fun onError(e: Int) {
                if (id != session) return
                if (e == SpeechRecognizer.ERROR_AUDIO) {
                    AcousticStreamAuditor.notifyRecognizerAudioError()
                }
                lastR?.let { commit(it) }
                if (id != session) return
                if (e == SpeechRecognizer.ERROR_INSUFFICIENT_PERMISSIONS) {
                    status = "صلاحية الميكروفون غير ممنوحة"
                    return
                }
                val wait = if (e == SpeechRecognizer.ERROR_RECOGNIZER_BUSY || e == SpeechRecognizer.ERROR_CLIENT) 400L else 80L
                restart(id, wait)
            }
            override fun onResults(b: Bundle?) {
                if (id != session) return
                AcousticStreamAuditor.notifyRecognizerAlive()
                val c = candidates(b)
                if (c != null) onHyp(c, true) else lastR?.let { commit(it) }
                restart(id, 0L)
            }
            override fun onPartialResults(b: Bundle?) {
                if (id != session) return
                AcousticStreamAuditor.notifyRecognizerAlive()
                candidates(b)?.let { onHyp(it, false) }
            }
            override fun onSegmentResults(segmentResults: Bundle) {
                if (id != session) return
                AcousticStreamAuditor.notifyRecognizerAlive()
                candidates(segmentResults)?.let { onHyp(it, false) }
            }
            override fun onEndOfSegmentedSession() {
                if (id != session) return
                lastR?.let { commit(it) }
                restart(id, 0L)
            }
        })
        val pipePfd = if (Build.VERSION.SDK_INT >= 33 && AcousticStreamAuditor.shouldUseAudioSourcePipe()) {
            AcousticStreamAuditor.openPipeForSpeechRecognizer {
                if (id == session) restart(id, 0L)
            }
        } else null
        r.startListening(Intent(RecognizerIntent.ACTION_RECOGNIZE_SPEECH).apply {
            putExtra(RecognizerIntent.EXTRA_LANGUAGE_MODEL, RecognizerIntent.LANGUAGE_MODEL_FREE_FORM)
            putExtra(RecognizerIntent.EXTRA_LANGUAGE, "ar-SA")
            putExtra(RecognizerIntent.EXTRA_PARTIAL_RESULTS, true)
            putExtra(RecognizerIntent.EXTRA_MAX_RESULTS, 10)
            putExtra(RecognizerIntent.EXTRA_CALLING_PACKAGE, ctx.packageName)
            putExtra(RecognizerIntent.EXTRA_SPEECH_INPUT_COMPLETE_SILENCE_LENGTH_MILLIS, 4500L)
            putExtra(RecognizerIntent.EXTRA_SPEECH_INPUT_POSSIBLY_COMPLETE_SILENCE_LENGTH_MILLIS, 3500L)
            putExtra(RecognizerIntent.EXTRA_SPEECH_INPUT_MINIMUM_LENGTH_MILLIS, 20000L)
            if (Build.VERSION.SDK_INT >= 33 && pipePfd != null) {
                putExtra(RecognizerIntent.EXTRA_AUDIO_SOURCE, pipePfd)
                putExtra(RecognizerIntent.EXTRA_AUDIO_SOURCE_CHANNEL_COUNT, 1)
                putExtra(RecognizerIntent.EXTRA_AUDIO_SOURCE_ENCODING, AudioFormat.ENCODING_PCM_16BIT)
                putExtra(RecognizerIntent.EXTRA_AUDIO_SOURCE_SAMPLING_RATE, 16000)
            }
        })
    }

    private fun restart(id: Int, delay: Long) {
        if (id != session) return
        if ((phase == Phase.GUIDED && !playing) || phase == Phase.RECITE) {
            h.postDelayed({ if (id == session) startRec() }, delay)
        }
    }

    /**
     * يستخرج الفرضيات من كلٍّ من RESULTS_RECOGNITION و UNSTABLE_TEXT:
     * - UNSTABLE_TEXT يحتوي على الكلمة الصوتية الخام التي ينطقها المستخدم في نفس اللحظة قبل أن يصححها النموذج اللغوي لـ Google!
     * - هذا يجعل التوهج الذهبي يتحرك فوراً من أول كلمة («اللَّهُ») ويلتقط الكلمات المتقاربة وأخطاء التشكيل قبل تبييضها!
     */
    private fun candidates(b: Bundle?): List<String>? {
        if (b == null) return null
        val stable = b.getStringArrayList(SpeechRecognizer.RESULTS_RECOGNITION)
        val unstable = b.getStringArrayList("android.speech.extra.UNSTABLE_TEXT")
        val ut = unstable?.firstOrNull()?.trim() ?: ""
        val out = ArrayList<String>()
        if (stable != null && stable.isNotEmpty()) {
            val st0 = stable[0].trim()
            if (ut.isNotEmpty()) {
                val combined = "$st0 $ut".trim()
                if (norm(combined).isNotEmpty()) out.add(combined)
            }
            for (s in stable) {
                val trimmed = s.trim()
                if (norm(trimmed).isNotEmpty() && !out.contains(trimmed)) {
                    out.add(trimmed)
                }
            }
        } else if (ut.isNotEmpty() && norm(ut).isNotEmpty()) {
            out.add(ut)
        }
        return if (out.isEmpty()) null else out
    }

    private fun onHyp(raw: List<String>, isFinal: Boolean) {
        if (phase != Phase.GUIDED && phase != Phase.RECITE) return
        val primary = Aligner.align(raw[0], sBase, isFinal)
        val r = primary ?: raw.drop(1).firstNotNullOfOrNull { Aligner.align(it, sBase, isFinal) }
        if (r == null) {
            if (isFinal) lastR?.let { commit(it) }
            return
        }

        // 1. فحص جميع الفرضيات البديلة (N-Best Acoustic Beams) لرصد:
        //    أ) أي مصيدة تشكيل أو تنوين أو كلمة قريبة في WORD_TRAPS
        //    ب) أي كلمة قريبة (isCloseWordNeighbor) ظهرت في البدائل الصوتية بينما صححها النموذج اللغوي في raw[0]
        val altResults = ArrayList<AlignResult>()
        val altLimit = min(raw.size, 8)
        for (k in 1 until altLimit) {
            val altR = Aligner.align(raw[k], sBase, isFinal) ?: continue
            altResults.add(altR)
            val maxW = min(WORDS.size, altR.last + 1)
            for (wi in sBase until maxW) {
                if (altR.trapHit[wi] && lockedWrongNotes[wi].isEmpty()) {
                    lockedWrongNotes[wi] = altR.notes[wi]
                    lockedWrongHeard[wi] = altR.heard[wi]
                }
            }
        }

        val completedLimit = min(WORDS.size, r.last + (if (isFinal) 1 else 0))
        for (wi in maxOf(sBase, r.first) until completedLimit) {
            if (lockedWrongNotes[wi].isNotEmpty()) continue
            if (r.st[wi] == WS.OK && altResults.isNotEmpty()) {
                for (aR in altResults) {
                    if (wi < aR.last && aR.subOrInsCost[wi] >= 1f && aR.heard[wi].isNotEmpty() &&
                        TashkeelAndMakhrajChecker.isCloseWordNeighbor(aR.heard[wi], NW[wi])
                    ) {
                        val diag = if (aR.notes[wi].isNotEmpty()) aR.notes[wi]
                        else TashkeelAndMakhrajChecker.diagnoseOrthographicError(wi, NW[wi], aR.heard[wi])
                        lockedWrongNotes[wi] = diag
                        lockedWrongHeard[wi] = aR.heard[wi]
                        break
                    }
                }
            }
        }

        // 2. فحص التشكيل والتجويد اللحظي:
        //    أ) الكلمات التي انتقل القارئ لما بعدها (wi < r.last) اكتمل نطقها 100% فنفحصها فوراً مع قص وادي الطاقة قبل الكلمة الجديدة
        //    ب) الكلمة الحالية (r.last) عند اكتمال حروفها نلتقط حركتها الأخيرة ونفحصها فور انتهاء نطق آخرها (380ms) حتى لا نفحصها قبل نطق حركتها!
        val immediateAuditEnd = if (isFinal) min(WORDS.size, r.last + 1) else min(WORDS.size, r.last)
        val auditStart = maxOf(sBase, maxOf(r.first, auditedUpToWord))
        if (immediateAuditEnd > auditStart) {
            val acousticErrs = AcousticStreamAuditor.auditCompletedWordsRange(
                wStart = auditStart,
                wEndExclusive = immediateAuditEnd,
                nextWordAlreadyStarted = !isFinal,
                isFinal = isFinal
            )
            for ((wi, errMsg) in acousticErrs) {
                if (wi in sBase until WORDS.size && lockedWrongNotes[wi].isEmpty()) {
                    lockedWrongNotes[wi] = errMsg
                    if (lockedWrongHeard[wi].isEmpty()) lockedWrongHeard[wi] = r.heard[wi]
                }
            }
            auditedUpToWord = immediateAuditEnd
        }
        if (!isFinal && r.last in sBase until WORDS.size && r.st[r.last] != null && auditedUpToWord <= r.last) {
            AcousticStreamAuditor.onWordStemReached(r.last)
            scheduleTailAuditForCurrentWord(r.last, r.heard[r.last])
        }

        // 3. إذا نطق القارئ في الموضع الحالي (r.last) كلمة مكتملة الحروف أو غير مطابقة، نقفل الخطأ فوراً من أول إطار قبل أن يصححه نموذج اللغة في الكلمة التالية!
        val lastW = r.last
        if (lastW in sBase until WORDS.size && lockedWrongNotes[lastW].isEmpty()) {
            val hLast = r.heard[lastW]
            val isFullLengthMismatch = hLast.length >= NW[lastW].length && hLast != NW[lastW]
            val isNotPrefix = hLast.length >= max(2, NW[lastW].length - 1) && !NW[lastW].startsWith(hLast)
            if (r.trapHit[lastW]) {
                lockedWrongNotes[lastW] = r.notes[lastW]
                lockedWrongHeard[lastW] = hLast
            } else if ((isFullLengthMismatch || isNotPrefix) && r.subOrInsCost[lastW] >= 0.7f) {
                val diag = if (r.notes[lastW].isNotEmpty()) r.notes[lastW]
                else TashkeelAndMakhrajChecker.diagnoseOrthographicError(lastW, NW[lastW], hLast)
                lockedWrongNotes[lastW] = diag
                lockedWrongHeard[lastW] = hLast
            }
        }

        // 4. تحديث حالات الكلمات وقفل أي كلمة مكتملة ثبت خطؤها فوراً
        var beep = false
        for (i in sBase until WORDS.size) {
            if (states[i] == WS.HINT) continue

            if (r.st[i] == WS.WRONG && (i < r.last || isFinal) && lockedWrongNotes[i].isEmpty()) {
                val diag = if (r.notes[i].isNotEmpty()) r.notes[i]
                else TashkeelAndMakhrajChecker.diagnoseOrthographicError(i, NW[i], r.heard[i])
                lockedWrongNotes[i] = diag
                lockedWrongHeard[i] = r.heard[i]
            }

            if (lockedWrongNotes[i].isNotEmpty()) {
                if (!beeped[i] && phase == Phase.RECITE) { beeped[i] = true; beep = true }
                states[i] = WS.WRONG
                notes[i] = lockedWrongNotes[i]
                if (lockedWrongHeard[i].isNotEmpty()) heard[i] = lockedWrongHeard[i]
                else if (r.heard[i].isNotEmpty()) heard[i] = r.heard[i]
                continue
            }

            val s = r.st[i]
            if (s == WS.WRONG && !beeped[i] && phase == Phase.RECITE) { beeped[i] = true; beep = true }
            states[i] = s ?: WS.PENDING
            if (s != null) {
                heard[i] = r.heard[i]
                notes[i] = r.notes[i]
            }
        }

        var decidedPrefix = sBase
        while (decidedPrefix < WORDS.size && states[decidedPrefix] != WS.PENDING) {
            decidedPrefix++
        }
        if (decidedPrefix > base) {
            base = decidedPrefix
        }

        if (beep) { try { tone?.startTone(ToneGenerator.TONE_PROP_BEEP, 180) } catch (e: Exception) { } }
        refreshCurrent()
        if (isFinal) {
            commit(r)
        } else {
            lastR = r
            if (allDecided() && !stopping) {
                stopping = true
                AcousticStreamAuditor.closeCurrentPipe()
                rec?.stopListening()
                val myId = session
                h.postDelayed({
                    if (myId == session && allDecided() && (phase == Phase.GUIDED || phase == Phase.RECITE)) {
                        lastR?.let { commit(it) }
                    }
                }, 320L)
            }
        }
    }

    private fun scheduleTailAuditForCurrentWord(targetW: Int, heardStr: String, postponeCount: Int = 0) {
        if (postponeCount == 0) {
            if (pendingTailAuditWord == targetW) return
            pendingTailAuditWord = targetW
        }
        val myId = session
        val delayMs = if (postponeCount > 0) 160L else if (targetW in setOf(1, 9, 19, 23, 34, 36, 39)) 480L else 360L
        h.postDelayed({
            if (myId != session || (phase != Phase.GUIDED && phase != Phase.RECITE)) return@postDelayed
            if (auditedUpToWord > targetW) return@postDelayed
            if (postponeCount < 3 && AcousticStreamAuditor.isCurrentlyVoicing()) {
                scheduleTailAuditForCurrentWord(targetW, heardStr, postponeCount + 1)
                return@postDelayed
            }
            val aStart = maxOf(sBase, auditedUpToWord)
            val aEnd = min(WORDS.size, targetW + 1)
            if (aEnd > aStart) {
                val errs = AcousticStreamAuditor.auditCompletedWordsRange(
                    wStart = aStart,
                    wEndExclusive = aEnd,
                    nextWordAlreadyStarted = false,
                    isFinal = false
                )
                auditedUpToWord = aEnd
                var beepNow = false
                for ((wi, errMsg) in errs) {
                    if (wi in sBase until WORDS.size && lockedWrongNotes[wi].isEmpty()) {
                        lockedWrongNotes[wi] = errMsg
                        if (lockedWrongHeard[wi].isEmpty()) lockedWrongHeard[wi] = heardStr
                        states[wi] = WS.WRONG
                        notes[wi] = errMsg
                        if (heard[wi].isEmpty()) heard[wi] = heardStr
                        if (!beeped[wi] && phase == Phase.RECITE) {
                            beeped[wi] = true
                            beepNow = true
                        }
                    }
                }
                if (beepNow) {
                    try { tone?.startTone(ToneGenerator.TONE_PROP_BEEP, 180) } catch (_: Exception) {}
                }
                refreshCurrent()
            }
        }, delayMs)
    }

    private fun commit(r: AlignResult) {
        val nb = if (r.st[r.last] != null || lockedWrongNotes[r.last].isNotEmpty()) r.last + 1 else r.last
        if (nb > base) base = nb
        lastR = null
        if (allDecided()) {
            if (phase == Phase.RECITE) finish() else if (phase == Phase.GUIDED) attemptDone()
        }
    }

    private fun attemptDone() {
        stopRec(); AcousticStreamAuditor.stopAll()
        val bad = states.count { it == WS.WRONG }
        val my = session
        if (bad <= GUIDED_TOLERANCE) {
            counter = (counter - 1).coerceAtLeast(0)
            if (counter == 0) {
                status = "أحسنت! ننتقل إلى التسميع…"
                h.postDelayed({ if (my == session && phase == Phase.GUIDED) goRecite() }, 900)
            } else {
                status = "قراءة صحيحة ✓ — المتبقي $counter"
                again(1300L)
            }
        } else {
            status = "لم تُحتسب القراءة: $bad كلمة بها خطأ (بالأحمر). اضغط على الكلمة الحمراء لمعرفة الخطأ، أو اضغط «ابدأ من أول الآية»."
        }
    }

    private fun again(ms: Long) {
        val my = session
        h.postDelayed({
            if (my == session && phase == Phase.GUIDED) {
                resetAttempt()
                status = "اقرأ الآية بصوتك…"
                startRec()
            }
        }, ms)
    }

    fun toggleAudio() {
        if (playing) { stopAudio(); if (phase == Phase.GUIDED) startRec(); return }
        stopRec(); playing = true
        player = MediaPlayer().apply {
            setAudioAttributes(AudioAttributes.Builder().setContentType(AudioAttributes.CONTENT_TYPE_MUSIC).build())
            setDataSource(AUDIO_URL)
            setOnPreparedListener { it.start() }
            setOnCompletionListener { stopAudio(); if (phase == Phase.GUIDED) startRec() }
            setOnErrorListener { _, _, _ ->
                stopAudio(); status = "تعذّر تشغيل الصوت (تحقق من الإنترنت)"
                if (phase == Phase.GUIDED) startRec()
                true
            }
            prepareAsync()
        }
    }

    private fun stopAudio() { player?.release(); player = null; playing = false }
    private fun stopRec() { session++; AcousticStreamAuditor.closeCurrentPipe(); rec?.destroy(); rec = null }
    fun release() { h.removeCallbacksAndMessages(null); stopRec(); AcousticStreamAuditor.stopAll(); stopAudio(); tone?.release() }
}

