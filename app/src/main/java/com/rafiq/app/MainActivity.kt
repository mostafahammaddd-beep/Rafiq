    fun isCloseWordNeighbor(heardNorm: String, expectedNorm: String): Boolean {
        val h = heardNorm.trim()
        val e = expectedNorm.trim()
        if (h.isEmpty() || e.isEmpty() || h == e) return false
        if (e.length >= 4 && h.length < 2) return false
        if (abs(h.length - e.length) > 3) return false
        val m = h.length
        val n = e.length
        val dp = Array(m + 1) { IntArray(n + 1) }
        for (i in 1..m) {
            for (j in 1..n) {
                dp[i][j] = if (h[i - 1] == e[j - 1]) dp[i - 1][j - 1] + 1 else max(dp[i - 1][j], dp[i][j - 1])
            }
        }
        val lcs = dp[m][n]
        val minReq = if (min(m, n) <= 2) 1 else if (min(m, n) <= 4) 2 else 3
        return lcs >= minReq
    }

    fun preprocessRawTokens(rawText: String, base: Int): List<String> {
        val tokens = rawText.trim().split(Regex("\\s+")).filter { it.isNotEmpty() }.toMutableList()
        if (tokens.isEmpty()) return emptyList()

        if (base <= 2) {
            val istiadha = setOf("اعوذ", "أعوذ", "بالله", "من", "الشيطان", "الرجيم")
            while (tokens.size > 1 && tokens[0] in istiadha) {
                tokens.removeAt(0)
            }
            if (tokens.size >= 4 && (tokens[0] == "بسم" || tokens[0] == "بإسم") && tokens[1] == "الله" &&
                tokens[2].contains("الرحمن") && tokens[3].contains("الرحيم")
            ) {
                repeat(4) { tokens.removeAt(0) }
            } else if (tokens.size >= 3 && (tokens[0] == "بسم" || tokens[0] == "بإسم") &&
                tokens[1].contains("الرحمن") && tokens[2].contains("الرحيم")
            ) {
                repeat(3) { tokens.removeAt(0) }
            }
        }

        val merged = ArrayList<String>(tokens.size)
        var i = 0
        while (i < tokens.size) {
            val tk = tokens[i]
            if ((tk == "و" || tk == "وَ") && i + 1 < tokens.size) {
                merged.add("و" + tokens[i + 1])
                i += 2
                continue
            }
            if ((tk == "ب" || tk == "بِ") && i + 1 < tokens.size &&
                tokens[i + 1] in setOf("ما", "إذنه", "اذنه", "شيء", "شئ")
            ) {
                merged.add("ب" + tokens[i + 1])
                i += 2
                continue
            }
            if (tk in setOf("ا", "أ", "ن", "ان", "تن") && merged.isNotEmpty()) {
                val prev = merged.last()
                val prevNorm = normRawWord(prev, preserveTanweenFath = false)
                if ((prevNorm == "سنه" || prevNorm == "سنت") && (tk == "ا" || tk == "أ")) {
                    merged[merged.lastIndex] = "سنتا"
                    i++
                    continue
                } else if ((prevNorm == "سنه" || prevNorm == "سنت") && tk in setOf("ن", "ان", "تن")) {
                    merged[merged.lastIndex] = "سنتن"
                    i++
                    continue
                } else if (prevNorm == "نوم" && (tk == "ا" || tk == "أ")) {
                    merged[merged.lastIndex] = "نوما"
                    i++
                    continue
                } else if (prevNorm == "نوم" && (tk == "ن" || tk == "ان")) {
                    merged[merged.lastIndex] = "نومن"
                    i++
                    continue
                } else if (prevNorm == "بشي" && (tk == "ا" || tk == "أ")) {
                    merged[merged.lastIndex] = "بشيئا"
                    i++
                    continue
                } else if (prevNorm == "بشي" && (tk == "ن" || tk == "ان")) {
                    merged[merged.lastIndex] = "بشيءن"
                    i++
                    continue
                }
            }
            merged.add(tk)
            i++
        }
        return merged
    }

    fun checkWordTrapAndDiacritics(rawToken: String, wordIdx: Int): String? {
        if (wordIdx !in WORDS.indices) return null
        val t = rawToken.trim()
        if (t.isEmpty()) return null

        val traps = WORD_TRAPS[wordIdx]
        if (traps != null) {
            val match = traps[t]
            if (match != null && match != "صحيح") return match
        }

        if (t.contains('ً')) {
            return if (wordIdx == 9) {
                "خطأ في التشكيل والتجويد: نطقتَ «سِنَةً» (بتنوين الفتح) والصواب «سِنَةٌ» (بتنوين الضم مع الإدغام بغنة في الواو وصلاً)."
            } else {
                "خطأ في التشكيل (التنوين/الإعراب): نطقتَ تنوين الفتح في «${WORDS[wordIdx]}» والصواب «${WORDS[wordIdx]}»."
            }
        }
        if (t.contains('ٍ') && wordIdx != 34) {
            return "خطأ في التشكيل (التنوين/الإعراب): نطقتَ تنوين الكسر في «${WORDS[wordIdx]}» والصواب «${WORDS[wordIdx]}»."
        }
        if (t.contains('ٌ') && wordIdx != 9 && wordIdx != 11) {
            return "خطأ في التشكيل (التنوين/الإعراب): نطقتَ تنوين الضم في «${WORDS[wordIdx]}» والصواب «${WORDS[wordIdx]}»."
        }

        val refW = WORDS[wordIdx]
        var refLastV: String? = null
        for (idx in refW.length - 1 downTo 0) {
            when (refW[idx]) {
                'َ', 'ً' -> { refLastV = "الفتحة"; break }
                'ُ', 'ٌ' -> { refLastV = "الضمة"; break }
                'ِ', 'ٍ' -> { refLastV = "الكسرة"; break }
                'ْ' -> { refLastV = "السكون"; break }
            }
        }
        val lastCh = t.last()
        val heardLastV: String? = when (lastCh) {
            'َ', 'ً' -> "الفتحة"
            'ُ', 'ٌ' -> "الضمة"
            'ِ', 'ٍ' -> "الكسرة"
            else -> null
        }
        if (heardLastV != null && refLastV != null && heardLastV != refLastV) {
            return "خطأ في التشكيل (آخر الكلمة / الإعراب): نطقتَ «$heardLastV» في آخر «$refW» والصواب «$refLastV»."
        }
        return null
    }

    fun diagnoseOrthographicError(wordIdx: Int, expectedNorm: String, heardNorm: String): String {
        val cleanHeard = heardNorm.replace("ً", "")
        if (heardNorm.isEmpty()) {
            return "لم أسمع هذه الكلمة منك (قد تكون تخطيتَها أثناء التسميع)."
        }
        if (heardNorm.contains('ً')) {
            return "خطأ في التشكيل (التنوين/الإعراب): نطقتَ تنوين الفتح في «${WORDS[wordIdx]}» والصواب «${WORDS[wordIdx]}»."
        }
        val msgs = LinkedHashSet<String>()
        val makhrajHints = mapOf(
            Pair('ذ', 'ز') to "إبدال الذال زاياً — احرص على إخراج طرف اللسان في الذال",
            Pair('ذ', 'د') to "إبدال الذال دالاً — احرص على إخراج طرف اللسان ورخاوة الذال",
            Pair('ظ', 'ز') to "إبدال الظاء زاياً — احرص على تفخيم الظاء وإطباقها وإخراج طرف اللسان",
            Pair('ظ', 'ذ') to "ترقيق الظاء فتخرج ذالاً — احرص على تفخيم الظاء وإطباقها",
            Pair('ظ', 'ض') to "خلط مخرج الظاء بالضاد — الظاء يخرج فيها طرف اللسان",
            Pair('ض', 'د') to "إبدال الضاد دالاً — احرص على تفخيم الضاد وإطباقها واستطالتها",
            Pair('ض', 'ز') to "إبدال الضاد زاياً — الضاد تخرج من حافتي اللسان مع الأضراس العليا",
            Pair('ض', 'ظ') to "إبدال الضاد ظاءً — لا تُخرج طرف اللسان في الضاد",
            Pair('ش', 'س') to "إبدال الشين سيناً — احرص على صفة التفشّي في الشين من وسط اللسان",
            Pair('س', 'ص') to "تفخيم السين فتخرج صاداً — السين حرف مستفل مرقّق",
            Pair('ص', 'س') to "ترقيق الصاد فتخرج سيناً — الصاد حرف مستعلٍ مطبق مفخّم",
            Pair('ط', 'ت') to "ترقيق الطاء فتخرج تاءً — احرص على تفخيم الطاء وإطباقها وترك الهمس",
            Pair('ت', 'ط') to "تفخيم التاء فتخرج طاءً — التاء حرف مرقّق مهموس",
            Pair('ق', 'ك') to "إبدال القاف كافاً — القاف مفخّمة من أقصى اللسان مع الحنك اللحمي",
            Pair('ح', 'ه') to "إبدال الحاء هاءً — الحاء من وسط الحلق والهاء من أقصاه",
            Pair('ع', 'ا') to "إبدال العين همزةً — حقّق مخرج العين من وسط الحلق",
            Pair('خ', 'غ') to "خلط الخاء بالغين — الخاء مهموسة والغين مجهورة"
        )

        if (expectedNorm.length == cleanHeard.length) {
            for (k in expectedNorm.indices) {
                val ec = expectedNorm[k]
                val hc = cleanHeard[k]
                if (ec != hc) {
                    val hint = makhrajHints[Pair(ec, hc)]
                    if (hint != null) {
                        msgs.add("خطأ في مخرج/صفة الحرف: $hint (نطقتَ «$hc» بدلاً من «$ec»).")
                    } else {
                        msgs.add("خطأ في نطق الحرف أو الكلمة: نطقتَ «$hc» بدلاً من «$ec».")
                    }
                }
            }
        } else if (cleanHeard.length < expectedNorm.length) {
            val missingChars = expectedNorm.toMutableList()
            for (c in cleanHeard) missingChars.remove(c)
            for (mc in missingChars) {
                if (mc in listOf('ا', 'و', 'ي')) {
                    msgs.add("خطأ في التجويد (المدّ) أو بنية الكلمة: إسقاط أو قصر حرف المدّ «$mc».")
                } else {
                    msgs.add("خطأ في الحروف أو بنية الكلمة: إسقاط حرف «$mc» من الكلمة.")
                }
            }
        } else {
            val extraChars = cleanHeard.toMutableList()
            for (c in expectedNorm) extraChars.remove(c)
            for (xc in extraChars) {
                if (xc == 'ا' && wordIdx in setOf(0, 5, 6, 8, 9, 11, 18, 22, 23, 25, 26, 33, 34, 36, 41, 45, 48, 49)) {
                    msgs.add("خطأ في التشكيل (الإعراب / التنوين): فتحتَ آخر الكلمة أو نطقتَ تنوين الفتح في «${WORDS[wordIdx]}».")
                } else if (xc == 'ن' && wordIdx in setOf(9, 11, 34)) {
                    msgs.add("خطأ في التجويد (الإدغام): أظهرتَ نون التنوين في «${WORDS[wordIdx]}» وحقها الإدغام.")
                } else {
                    msgs.add("خطأ في الكلمة أو الحروف: زيادة حرف «$xc» (نطقتَ كلمة قريبة أو زدتَ حرفاً).")
                }
            }
        }

        val sb = StringBuilder()
        if (msgs.isNotEmpty()) {
            sb.append(msgs.joinToString("\n• ", prefix = "• ")).append("\n\n")
        }
        sb.append("سمعتُ منك: «").append(heardNorm).append("»\nوالصواب: ").append(WORDS[wordIdx])
        return sb.toString()
    }
